import { motion } from "framer-motion";
import { FileDown, Loader2 } from "lucide-react";
import { useState } from "react";
import { projectInfo, tasks, getStatusCounts, getOverallProgress } from "@/data/projectData";

const ExportReport = () => {
  const [loading, setLoading] = useState(false);

  const exportReport = () => {
    setLoading(true);

    const counts = getStatusCounts();
    const progress = getOverallProgress();
    const today = new Date().toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });

    const lines = [
      `╔══════════════════════════════════════════════════════════════╗`,
      `║       FABULOUZZ TECHNOLOGIES — PROJECT STATUS REPORT       ║`,
      `╚══════════════════════════════════════════════════════════════╝`,
      ``,
      `Report Date: ${today}`,
      ``,
      `── PROJECT INFORMATION ───────────────────────────────────────`,
      `  Project Title  : ${projectInfo.title}`,
      `  Reference       : ${projectInfo.projectRef}`,
      `  Client          : ${projectInfo.client}`,
      `  Location        : ${projectInfo.location}`,
      `  Company         : ${projectInfo.company}`,
      `  Project Manager : ${projectInfo.projectManager}`,
      `  Reporting To    : ${projectInfo.reportingTo}`,
      `  Project Engineer: ${projectInfo.projectEngineer}`,
      `  Start Date      : ${projectInfo.startDate}`,
      `  End Date        : ${projectInfo.endDate}`,
      ``,
      `── OVERALL PROGRESS ─────────────────────────────────────────`,
      `  Progress: ${progress}%`,
      `  Completed: ${counts.completed} | Processing: ${counts.processing} | Initiating: ${counts.initiating} | Planning: ${counts.planning}`,
      `  Total Tasks: ${counts.total}`,
      ``,
      `── TASK BREAKDOWN ───────────────────────────────────────────`,
      `  #  | Status      | Days | Task Name`,
      `  ---|-------------|------|------------------------------------`,
    ];

    tasks.forEach(t => {
      lines.push(
        `  ${String(t.id).padStart(2, "0")} | ${t.status.padEnd(11)} | ${String(t.duration).padStart(4)} | ${t.name}`
      );
    });

    lines.push(``);
    lines.push(`── END OF REPORT ────────────────────────────────────────────`);
    lines.push(`  Generated by SightLine Project Command Center`);
    lines.push(`  Powered by Fabulouzz Technologies`);

    const blob = new Blob([lines.join("\n")], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `SightLine_Report_${projectInfo.projectRef}_${today.replace(/\s/g, "-")}.txt`;
    a.click();
    URL.revokeObjectURL(url);

    setTimeout(() => setLoading(false), 500);
  };

  return (
    <motion.button
      onClick={exportReport}
      whileHover={{ scale: 1.05 }}
      whileTap={{ scale: 0.95 }}
      disabled={loading}
      className="flex items-center gap-2 px-3 py-1.5 rounded-full text-xs font-medium border border-primary/30 text-primary hover:bg-primary/10 transition-colors disabled:opacity-50"
    >
      {loading ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <FileDown className="w-3.5 h-3.5" />}
      <span className="hidden sm:inline">Export</span>
    </motion.button>
  );
};

export default ExportReport;
